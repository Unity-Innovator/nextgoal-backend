package com.example.genz.community;

import java.nio.charset.StandardCharsets;
import java.sql.DriverManager;
import java.sql.SQLException;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;
import org.junit.jupiter.api.Test;

import com.example.genz.community.post.enums.PostType;

class PostTypeConstraintMigrationTest {
    @Test
    void migrationPreservesExistingPostsAndAllowsEveryCurrentPostType() throws Exception {
        try (var connection = DriverManager.getConnection(
                "jdbc:h2:mem:post_type_migration;MODE=PostgreSQL", "sa", "");
             var statement = connection.createStatement()) {
            statement.execute("""
                    CREATE TABLE posts (
                        post_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        post_type VARCHAR(30) NOT NULL,
                        content VARCHAR(200),
                        CONSTRAINT posts_post_type_check CHECK (post_type IN (
                            'GOAL_SUCCESS', 'MILESTONE', 'TIP', 'EXPERIENCE', 'LIFE_UPDATE'
                        ))
                    )
                    """);
            statement.execute("INSERT INTO posts (post_type, content) VALUES ('LIFE_UPDATE', 'Keep my post')");
            assertThrows(SQLException.class, () -> statement.execute(
                    "INSERT INTO posts (post_type) VALUES ('SHARED_POST')"));

            try (var resource = getClass().getResourceAsStream(
                    "/db/migration/V27__allow_shared_post_type.sql")) {
                assertNotNull(resource);
                var migration = new String(resource.readAllBytes(), StandardCharsets.UTF_8);
                // Also prove an already-repaired database can apply this safely.
                for (int attempt = 0; attempt < 2; attempt++) {
                    for (var sql : migration.split(";")) {
                        if (!sql.isBlank()) statement.execute(sql);
                    }
                }
            }
            for (PostType type : PostType.values()) {
                try (var insert = connection.prepareStatement("INSERT INTO posts (post_type) VALUES (?)")) {
                    insert.setString(1, type.name());
                    assertEquals(1, insert.executeUpdate());
                }
            }
            assertThrows(SQLException.class, () -> statement.execute(
                    "INSERT INTO posts (post_type) VALUES ('INVALID_TYPE')"));
            try (var result = statement.executeQuery("SELECT content FROM posts WHERE content IS NOT NULL")) {
                assertTrue(result.next());
                assertEquals("Keep my post", result.getString(1));
            }
        }
    }
}
